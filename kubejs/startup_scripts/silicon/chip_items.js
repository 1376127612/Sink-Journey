// ============================================================
// 光刻线物品注册（startup）
// ------------------------------------------------------------
// 只注册物品，不做逻辑：晶圆纯度、掩模、激光头、测试规格单、分级芯片。
// 配方全在 server_scripts/silicon/litho_recipes.js。
// 光刻机是 MMCR 机器，见 startup_scripts/silicon/litho_machines.js。
//
// 贴图目录（补图时放这里，缺图不影响运行，只是格子发白）：
//   kubejs/assets/kubejs/textures/item/<name>.png
// 数量：晶圆 3（W1 复用 IU 的晶圆 494）+ 掩模 6 + 激光头 4 + 规格单 4
//       + 曝光晶圆 24 + 分级裸片 24
// ============================================================

StartupEvents.registry('item', event => {
    const add = (id, name, tip) => {
        const it = event.create(id).displayName(name)
        if (tip) it.tooltip(tip)
    }

    // ---------- 晶圆：W1 用 IU 的 494，这里注册 W2–W4 ----------
    add('wafer_9n', '9N 高纯晶圆', '§7西门子法料直拉切片，可做 90nm 及以下')
    add('wafer_11n', '11N 超高纯晶圆', '§7硅烷裂解料切片，可做 28nm / 7nm')
    add('wafer_12n', '12N 极限纯晶圆', '§7磁控直拉料切片，只有它能做 3nm')

    // ---------- 四条提纯工艺的中间产物 ----------
    add('siemens_poly', '西门子多晶硅棒', '§7三氯硅烷精馏后高温沉积，9N')
    add('mono_9n', '9N 单晶硅', '§7西门子棒的直拉产物，进激光处理厂切片')
    add('poly_11n', '11N 多晶硅', '§7硅烷裂解沉积，11N；qmd 晶柱也吃它')
    add('mono_11n', '11N 单晶硅', '§7硅烷料的直拉产物，进激光处理厂切片')
    add('mcz_coil', '铌钛超导线圈', '§7磁控直拉炉的磁场线圈，每批有损耗')

    // ---------- qmd 器件支线：T4 器件级晶棒与晶圆 ----------
    add('boule_12n', '器件级单晶硅棒', '§7磁控直拉，12N 低氧；切器件级晶圆')
    add('device_wafer', '器件级晶圆', '§7qmd 器件线的 12N 晶圆，掺杂后做处理器')
    add('device_n_doped', '器件级 N 型片', '§7中子嬗变掺磷')
    add('device_p_doped', '器件级 P 型片', '§7硼扩散掺硼')


    // ---------- 掩模：一代一片，对应工艺节点 ----------
    add('mask_1p5u', '掩模 M1 · 1.5µm', '§7线宽粗，容错高')
    add('mask_800n', '掩模 M2 · 800nm', '§7i-line 时代的量产片')
    add('mask_90n', '掩模 M3 · 90nm', '§7DUV，需要 9N 晶圆')
    add('mask_28n', '掩模 M4 · 28nm', '§7浸没式，需要 11N 晶圆')
    add('mask_7n', '掩模 M5 · 7nm', '§7多重曝光，需要 11N 晶圆')
    add('mask_3n', '掩模 M6 · 3nm', '§7只有 EUV + 12N 才做得出来')

    // ---------- 激光头：耗材，精度越高良率越高 ----------
    add('lens_glass', '激光头 H1 · 玻璃透镜', '§7便宜，报废率高')
    add('lens_quartz', '激光头 H2 · 石英镜头', '§7i-line 主力')
    add('lens_caf2', '激光头 H3 · 氟化钙镜头', '§7DUV 浸没用，透过率好')
    add('lens_multilayer', '激光头 H4 · 多层膜反射镜', '§7EUV 专用，反射率最高')

    // ---------- 测试规格单：决定这一批按哪一档筛选 ----------
    add('spec_i3', '测试规格单 · i3', '§7按最低规格筛选，几乎全过')
    add('spec_i5', '测试规格单 · i5', '§7中低规格')
    add('spec_i7', '测试规格单 · i7', '§7主流规格')
    add('spec_i9', '测试规格单 · i9', '§7顶配规格，报废率最高')

    // ---------- 曝光晶圆：6 代掩模 × 4 级晶圆 ----------
    // 光刻机只出这个；它记录「哪一代掩模打在哪一级晶圆上」，切割时按晶圆等级算裸片数。
    const nodes = ['1.5µm', '800nm', '90nm', '28nm', '7nm', '3nm']
    for (let m = 1; m <= 6; m++) {
        for (let w = 1; w <= 4; w++) {
            add(`exposed_m${m}_w${w}`, `${nodes[m - 1]} 曝光晶圆 · W${w}`, '§7已曝光，待切割分选')
        }
    }

    // ---------- 分级裸片：6 代 × 4 档 ----------
    const grades = ['i3', 'i5', 'i7', 'i9']
    for (let m = 1; m <= 6; m++) {
        for (const g of grades) {
            add(`chip_m${m}_${g}`, `${nodes[m - 1]} 裸片 · ${g}`,
                g === 'i9' ? '§7顶配裸片，可封装成 QFP 芯片' : '§7降档裸片，可按档位向下通用')
        }
    }
})
