// ============================================================
// 彻底封禁村民 (minecraft:villager)
//
// 策略：拦截实体加入世界 (EntityJoinLevelEvent)。
//   - 天然生成、村庄结构生成、繁殖、刷怪蛋、刷怪笼、指令生成的村民
//     在加入世界时全部被取消，不会出现。
//   - 已经存在的村民在所在区块重新加载时也会走这一事件，
//     因此同样会被清除。
//   - 只针对 minecraft:villager，不影响流浪商人、僵尸村民等其他生物。
// ============================================================

EntityEvents.spawned(event => {
    if (event.entity.type == 'minecraft:villager') {
        event.cancel()
    }
})

// ============================================================
// 封禁村民交易
//
// 第二层保险：由于“治疗僵尸村民”等途径产生的村民可能不会立刻触发
// 加入世界事件，这里再拦截玩家对村民的右键交互，
// 让交易界面根本无法打开（主副手都会被拦截）。
// ============================================================

ItemEvents.entityInteracted(event => {
    if (event.target.type == 'minecraft:villager') {
        event.cancel()
    }
})
