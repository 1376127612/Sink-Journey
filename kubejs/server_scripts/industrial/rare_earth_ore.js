// ============================================================
// 独居石矿的掉落
// ------------------------------------------------------------
// 稀土湿法线（RARE_EARTH_LINE.md）的进料是独居石：4 份浮选出 1 份精矿。
// 一块独居石矿掉 2 份，正好对上一份原矿换半份精矿的老口径
// （原先 1 份稀土原矿 → 2 碎 → 2 净碎 → 0.5 精矿）。
//
// 顺带把矿石方块本身从掉落里去掉：独居石矿只作为矿源存在，
// 不需要能被玩家搬回家摆着（也不需要丝触版本）。
// ============================================================

BlockEvents.drops('kubejs:monazite_ore', event => {
    event.removeItem('kubejs:monazite_ore')
    event.addItem('2x kubejs:monazite')
})
