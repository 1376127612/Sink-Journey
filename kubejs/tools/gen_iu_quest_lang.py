def managed(line):
    m = re.match(r"^	(quest\.[0-9A-F]{16}|chapter\.[0-9A-F]{16})\.", line)
    if not m:
        return False
    key = m.group(1)
    return key.startswith(MANAGED_PREFIX) or key in MANAGED_EXACT

